let currentLanguage = localStorage.getItem("ruralcare_lang") || "en";

function setLanguage(lang) {
    if (!I18N[lang]) lang = "en";
    currentLanguage = lang;
    localStorage.setItem("ruralcare_lang", lang);
    applyTranslations();
    document.documentElement.lang = lang;
}

function t(key) {
    if (I18N[currentLanguage] && I18N[currentLanguage][key]) {
        return I18N[currentLanguage][key];
    }
    if (I18N["en"] && I18N["en"][key]) {
        return I18N["en"][key];
    }
    return key;
}

function applyTranslations() {
    document.querySelectorAll("[data-i18n]").forEach(elem => {
        const key = elem.getAttribute("data-i18n");
        const translation = t(key);
        if (translation) {
            if (elem.tagName === "INPUT" || elem.tagName === "TEXTAREA") {
                elem.placeholder = translation;
            } else {
                elem.innerHTML = translation;
            }
        }
    });

    // Update active state in language pills
    document.querySelectorAll(".lang-btn").forEach(btn => {
        if (btn.getAttribute("data-lang") === currentLanguage) {
            btn.classList.add("active");
        } else {
            btn.classList.remove("active");
        }
    });
}
